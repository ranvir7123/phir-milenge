export function Icon({ name, size = 20, style, label }: { name: IconName; size?: number; style?: CSSProperties; label?: string }) {
  return (
    <svg
      className="pm-icon"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={1.8}
      strokeLinecap="round"
      strokeLinejoin="round"
      style={style}
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
    >
      {paths[name]}
    </svg>
  );
}

/** The warning triangle, always in the warning colour and always followed by its word. */
export function Warn({ size = 20 }: { size?: number }) {
  return <Icon name="alert" size={size} style={{ color: 'var(--warning)', flex: 'none' }} label="Warning" />;
}

